  code += `                if rating_match:\n`;
  code += `                    data["rating"] = rating_match.group(1)\n`;
  code += `                \n`;
  code += `                plot_match = re.search(r'<div[^>]*class="[^"]*(?:plot|description)[^"]*"[^>]*>([^<]+)', html, re.I)\n`;
