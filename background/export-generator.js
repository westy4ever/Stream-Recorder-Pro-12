  code += `                            "name": "Server",\n`;
  code += `                            "url": server_url,\n`;
  code += `                            "quality": quality\n`;
  code += `                        })\n`;
  code += `            \n`;
  code += `            self._cache[cache_key] = data\n`;
  code += `            log("${siteName}: Extracted page: {} ({} servers)".format(\n`;
