  code += `                    data["plot"] = plot_match.group(1).strip()\n`;
  code += `                \n`;
  code += `                server_matches = re.findall(r'<a[^>]*href="([^"]*(?:streamruby|dood|\\.m3u8)[^"]*)"[^>]*>', html, re.I)\n`;
