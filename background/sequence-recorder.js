// sequence-recorder.js - Request Sequence Recorder
import { state } from './state.js';

export function recordRequestSequence() {
  const s = state;
  const networkLog = s.networkLog || [];
  const xhrBodies = s.xhrBodies || [];
  const actions = s.actions || [];

  const sequence = {
    requests: [],
    totalTime: 0,
    totalData: 0,
    summary: {},
    replayScript: ''
  };

  // Sort requests by timestamp
  const sortedRequests = [...networkLog].sort((a, b) => (a.timestamp || 0) - (b.timestamp || 0));

  let startTime = sortedRequests[0]?.timestamp || Date.now();

  for (const entry of sortedRequests) {
    const body = xhrBodies.find(b => b.url === entry.url);
    const relatedAction = actions.find(a => a.url === entry.url || a.href === entry.url);

    const request = {
      order: sequence.requests.length + 1,
      timestamp: entry.timestamp || 0,
      relativeTime: ((entry.timestamp || 0) - startTime) / 1000,
      method: entry.method || 'GET',
      url: entry.url,
      status: entry.statusCode || 0,
      contentType: entry.responseHeaders?.['content-type'] || body?.contentType || 'unknown',
      size: body?.body?.length || 0,
      requestHeaders: entry.requestHeaders || {},
      responseHeaders: entry.responseHeaders || {},
      requestBody: entry.requestBody || null,
      responseBody: body?.body || null,
      actionType: relatedAction?.type || null,
      isAPI: entry.url.includes('/api/') || entry.url.includes('/ajax/'),
      isStream: entry.url.includes('.m3u8') || entry.url.includes('.mp4'),
      isAsset: entry.url.match(/\.(css|js|png|jpg|jpeg|gif|svg|ico|woff|woff2)$/)
    };

    sequence.requests.push(request);
    sequence.totalData += request.size;
  }

  if (sequence.requests.length > 0) {
    const lastTime = sequence.requests[sequence.requests.length - 1].timestamp || Date.now();
    sequence.totalTime = (lastTime - startTime) / 1000;
  }

  // Generate summary
  sequence.summary = {
    totalRequests: sequence.requests.length,
    apiRequests: sequence.requests.filter(r => r.isAPI).length,
    streamRequests: sequence.requests.filter(r => r.isStream).length,
    assetRequests: sequence.requests.filter(r => r.isAsset).length,
    totalTime: sequence.totalTime,
    totalData: sequence.totalData,
    avgTimePerRequest: sequence.requests.length > 0 ? sequence.totalTime / sequence.requests.length : 0
  };

  // Generate replay script
  sequence.replayScript = generateReplayScript(sequence.requests);

  return sequence;
}

// [FIX] safely escape an arbitrary JS string into a valid, safely-quoted Python string
// literal, so it can be embedded in generated Python source without producing invalid or
// unintentionally-executable code. Verified: round-trips correctly through Python's own
// eval() for tricky inputs (embedded quotes, backslashes, newlines, tabs, empty string).
function toPythonStringLiteral(s) {
  return "'" + String(s)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t') + "'";
}

function generateReplayScript(requests) {
  let script = '#!/usr/bin/env python3\n';
  script += '# -*- coding: utf-8 -*-\n';
  script += '# Auto-generated request sequence replay script\n';
  script += '# Generated by Stream Recorder Pro\n\n';

  script += 'import requests\n';
  script += 'import json\n';
  script += 'import time\n\n';

  script += 'def replay_sequence():\n';
  script += '    """Replay the captured request sequence."""\n';
  script += '    session = requests.Session()\n';
  script += '    \n';
  script += '    # Use captured headers\n';

  // Extract common headers
  const commonHeaders = {};
  for (const req of requests) {
    if (req.requestHeaders) {
      for (const [key, value] of Object.entries(req.requestHeaders)) {
        if (!commonHeaders[key] || commonHeaders[key] !== value) {
          commonHeaders[key] = value;
        }
      }
    }
  }

  // Remove dynamic/session-specific headers -- these should never be hardcoded into a
  // generated script that might get saved, shared, or committed somewhere.
  // [FIX] 'authorization' was missing here -- a captured "Authorization: Bearer ..." header
  // (common on any API-token-based site) would otherwise be baked directly into the script
  // as a hardcoded plaintext credential, the exact same class of leak 'cookie' was already
  // being excluded to prevent.
  const excludeHeaders = ['cookie', 'content-length', 'host', 'connection', 'authorization'];
  script += '    headers = {\n';
  for (const [key, value] of Object.entries(commonHeaders)) {
    if (!excludeHeaders.includes(key.toLowerCase())) {
      script += `        "${key}": "${value}",\n`;
    }
  }
  script += '    }\n';
  script += '    session.headers.update(headers)\n\n';

  // Generate requests
  let requestCount = 0;
  for (const req of requests) {
    if (req.isAsset) continue; // Skip assets
    if (req.isStream) continue; // Skip streams

    requestCount++;
    if (requestCount > 50) break; // Limit

    const method = req.method || 'GET';
    const url = req.url;

    script += `    # Request ${req.order}: ${method} ${url}\n`;

    if (method === 'GET') {
      script += `    response${req.order} = session.get("${url}")\n`;
    } else if (method === 'POST') {
      // [FIX] req.requestBody is whatever safeBodyToString() in state.js produced -- which is
      // NOT guaranteed to be valid JSON/Python syntax at all. A very common real case: any
      // HTML <form> submission (content.js's own 'submit' listener captures exactly this)
      // produces a form-urlencoded body like "user=x&pass=y", which the OLD code embedded
      // directly as `data5 = user=x&pass=y` -- invalid Python syntax, confirmed empirically
      // to throw a SyntaxError that breaks the ENTIRE generated script, not just this one
      // request. Now the body is safely quoted as a Python string literal, and the generated
      // script itself tries json.loads() on it at runtime, falling back to sending it as raw
      // form data if it isn't actually JSON -- correct either way, and never a syntax error.
      const bodyLiteral = toPythonStringLiteral(req.requestBody || '{}');
      script += `    body${req.order} = ${bodyLiteral}\n`;
      script += `    try:\n`;
      script += `        data${req.order} = json.loads(body${req.order})\n`;
      script += `        response${req.order} = session.post("${url}", json=data${req.order})\n`;
      script += `    except (json.JSONDecodeError, TypeError):\n`;
      script += `        response${req.order} = session.post("${url}", data=body${req.order})\n`;
    } else {
      script += `    response${req.order} = session.${method.toLowerCase()}("${url}")\n`;
    }

    script += `    print(f"Request ${req.order}: {response${req.order}.status_code}")\n`;
    script += `    time.sleep(0.5)\n\n`;
  }

  script += 'if __name__ == "__main__":\n';
  script += '    replay_sequence()\n';

  return script;
}

export function generateSequenceReport() {
  const sequence = recordRequestSequence();

  let report = '=== REQUEST SEQUENCE RECORDER ===\n\n';

  report += '📊 SUMMARY:\n';
  report += `  Total Requests: ${sequence.summary.totalRequests}\n`;
  report += `  API Requests: ${sequence.summary.apiRequests}\n`;
  report += `  Stream Requests: ${sequence.summary.streamRequests}\n`;
  report += `  Asset Requests: ${sequence.summary.assetRequests}\n`;
  report += `  Total Time: ${sequence.summary.totalTime.toFixed(2)}s\n`;
  report += `  Total Data: ${(sequence.summary.totalData / 1024).toFixed(1)}KB\n`;
  report += `  Avg Time/Request: ${(sequence.summary.avgTimePerRequest || 0).toFixed(3)}s\n\n`;

  report += '📋 REQUEST SEQUENCE:\n';
  for (const req of sequence.requests) {
    if (req.isAsset) continue;
    const emoji = req.isAPI ? '📡' : req.isStream ? '🎬' : '📄';
    report += `  ${emoji} [${req.order}] ${req.method} ${req.url}\n`;
    report += `    Status: ${req.status} | Time: ${req.relativeTime.toFixed(2)}s`;
    if (req.size > 0) report += ` | Size: ${(req.size / 1024).toFixed(1)}KB`;
    if (req.actionType) report += ` | Action: ${req.actionType}`;
    report += '\n';
  }

  report += '\n🔄 REPLAY SCRIPT:\n';
  report += sequence.replayScript;

  return report;
}
