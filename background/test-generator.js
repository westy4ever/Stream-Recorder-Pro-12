import { state } from './state.js';

export function generateTests(siteName, capturedData) {
  const s = state;
  const networkLog = capturedData?.networkLog || s.networkLog || [];
  const xhrBodies = capturedData?.xhrBodies || s.xhrBodies || [];
  const contentPipeline = capturedData?.contentPipeline || s.contentPipeline || {};

  const className = siteName.charAt(0).toUpperCase() + siteName.slice(1) + 'Extractor';
  const safeName = siteName.toLowerCase().replace(/[^a-z0-9]/g, '_');

  // Generate test data from captured content
  const testData = {
    sampleCategory: contentPipeline.movieList?.[0]?.url || '/category/english-movies/',
    sampleMovie: contentPipeline.movieList?.[0]?.url || '/movie/example',
    sampleSearch: contentPipeline.movieList?.[0]?.title || 'avengers',
    sampleStream: null
  };

  // Find a stream URL for testing
  for (const body of xhrBodies) {
    if (body.body && (body.body.includes('.m3u8') || body.body.includes('.mp4'))) {
      const urls = body.body.match(/https?:\/\/[^\s"']+\.(?:m3u8|mp4)[^\s"']*/g) || [];
      if (urls.length > 0) {
        testData.sampleStream = urls[0];
        break;
      }
    }
  }

  return generateTestFile(siteName, className, safeName, testData);
}

